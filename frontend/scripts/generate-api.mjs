// Generate the TypeScript transport types from the committed OpenAPI contract.
//
// The contract source is `contracts/openapi-v1.json`. The backend test suite already fails when
// the live FastAPI schema differs from that snapshot, so this script closes the chain: a contract
// change must update the snapshot, and the snapshot must then be reflected in `src/api/schema.d.ts`.
//
//   node scripts/generate-api.mjs           write src/api/schema.d.ts
//   node scripts/generate-api.mjs --check   fail when the committed file is stale

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const SPEC_URL = new URL('../../contracts/openapi-v1.json', import.meta.url)
const TARGET_URL = new URL('../src/api/schema.d.ts', import.meta.url)
const HEADER = [
  '/**',
  ' * Generated by scripts/generate-api.mjs from contracts/openapi-v1.json.',
  ' * Do not edit by hand: run `npm run api:generate` after a backend contract change.',
  ' */',
  '',
  '',
].join('\n')

const check = process.argv.includes('--check')
const specification = JSON.parse(await readFile(SPEC_URL, 'utf-8'))
const generated = HEADER + astToString(await openapiTS(specification))
const targetPath = fileURLToPath(TARGET_URL)

if (check) {
  let committed = null
  try {
    committed = await readFile(TARGET_URL, 'utf-8')
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error
  }
  if (committed !== generated) {
    console.error(
      `${targetPath} does not match contracts/openapi-v1.json.\n` +
        'The backend contract changed: run `npm --prefix frontend run api:generate` and commit the result.',
    )
    process.exit(1)
  }
  console.log('Transport types match the committed OpenAPI contract.')
} else {
  await writeFile(TARGET_URL, generated, 'utf-8')
  console.log(`Wrote ${targetPath}`)
}
